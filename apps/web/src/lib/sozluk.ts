const SOZLUKLER: Record<Dil, WebSozluk> = { tr, en, de, ru };

/** Dile bağlı metin fonksiyonu: const m = metinler(dil); m('begeni', { n: 3 }) */
export function metinler(dil: Dil) {
  const s = SOZLUKLER[dil] ?? tr;
  return (anahtar: keyof WebSozluk, d?: Degiskenler) => doldur(s[anahtar] ?? tr[anahtar], d);
}

export type Metin = ReturnType<typeof metinler>;
